import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { A1_COURSE } from '../src/content/a1';

/**
 * Generates the pre-recorded Tagalog audio used by AudioButton.
 *
 * The static site must work without a Filipino speech voice installed in the
 * learner's browser. This script renders every text the UI can play, names the
 * file by a stable hash and writes src/content/audio-manifest.ts.
 *
 * Requires the Python edge-tts package:
 *   python3 -m pip install --user edge-tts
 *
 * Run:
 *   npm run audio:generate
 */

const VOICE = process.env.TAGALOG_TTS_VOICE ?? 'fil-PH-BlessicaNeural';
const RATE = process.env.TAGALOG_TTS_RATE ?? '-5%';
const OUTPUT_DIR = resolve('public/audio');
const MANIFEST_PATH = resolve('src/content/audio-manifest.ts');
const CONCURRENCY = 4;

function collectTexts(): string[] {
  const texts = new Set<string>();
  for (const unit of A1_COURSE.units) {
    for (const lesson of unit.lessons) {
      for (const entry of lesson.vocabulary) texts.add(entry.audioText ?? entry.tagalog);
      for (const section of lesson.sections) {
        if (section.type === 'dialogue') {
          for (const line of section.lines) texts.add(line.audioText ?? line.tagalog);
        }
        if (section.type === 'pattern') {
          for (const example of section.examples) texts.add(example.tagalog);
        }
      }
      for (const exercise of lesson.exercises) {
        if (exercise.type === 'listening' || exercise.type === 'dictation') texts.add(exercise.audioText);
      }
      for (const question of lesson.check.questions) {
        if (question.type === 'listening' || question.type === 'dictation') texts.add(question.audioText);
      }
    }
  }
  return [...texts].sort((a, b) => a.localeCompare(b, 'en'));
}

function fileFor(text: string): string {
  const hash = createHash('sha1').update(text).digest('hex').slice(0, 16);
  return join(OUTPUT_DIR, `${hash}.mp3`);
}

function runEdgeTts(text: string, output: string): Promise<void> {
  return new Promise((resolvePromise, reject) => {
    execFile(
      'python3',
      ['-m', 'edge_tts', '--voice', VOICE, '--rate', RATE, '--text', text, '--write-media', output],
      { env: process.env, maxBuffer: 1024 * 1024 },
      (error) => {
        if (error) reject(error);
        else resolvePromise();
      },
    );
  });
}

async function withRetry(text: string, output: string, attempts = 3): Promise<void> {
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      await runEdgeTts(text, output);
      if (existsSync(output) && statSync(output).size > 500) return;
    } catch {
      // Retry transient network or service errors.
    }
    await new Promise((resolvePromise) => setTimeout(resolvePromise, 800 * attempt));
  }
  throw new Error(`Could not generate audio for: ${text}`);
}

async function main() {
  if (!existsSync(OUTPUT_DIR)) mkdirSync(OUTPUT_DIR, { recursive: true });

  const texts = collectTexts();
  const manifest: Record<string, string> = {};
  const missing: string[] = [];

  for (const text of texts) {
    const file = fileFor(text);
    manifest[text] = `/audio/${file.split('/').pop()}`;
  }

  const queue = texts.filter((text) => {
    const file = fileFor(text);
    return !(existsSync(file) && statSync(file).size > 500);
  });

  console.log(`${texts.length} unique texts, ${queue.length} need audio.`);

  let done = 0;
  let failed = 0;
  async function worker() {
    while (queue.length > 0) {
      const text = queue.shift();
      if (!text) return;
      try {
        await withRetry(text, fileFor(text));
      } catch {
        failed += 1;
        missing.push(text);
      }
      done += 1;
      if (done % 25 === 0 || done === texts.length) {
        console.log(`  ${done}/${texts.length} processed, ${failed} failed`);
      }
    }
  }

  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  const lines = Object.entries(manifest)
    .sort(([a], [b]) => a.localeCompare(b, 'en'))
    .map(([text, path]) => `  ${JSON.stringify(text)}: ${JSON.stringify(path)},`);

  writeFileSync(
    MANIFEST_PATH,
    `// Generated by scripts/generate-audio.ts. Do not edit by hand.\n` +
      `export const AUDIO_MANIFEST: Record<string, string> = {\n${lines.join('\n')}\n};\n`,
  );

  console.log(`Manifest written to ${MANIFEST_PATH}`);
  if (missing.length > 0) {
    console.error(`Missing audio (${missing.length}):`);
    for (const text of missing.slice(0, 20)) console.error(`- ${text}`);
    process.exit(1);
  }
}

void main();
