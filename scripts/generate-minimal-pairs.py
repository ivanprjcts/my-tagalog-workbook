#!/usr/bin/env python3
"""
Build the stress/glottal-stop minimal pairs with a Spanish voice.

The main Filipino TTS voice ignores written stress marks, and its syllable
rendering can sound English-influenced. For these words the relevant contrasts
are stress and the final glottal stop, and Spanish vowels/consonants are closer
to the target sounds.

Pairs:
  báka (cow)      vs baká (maybe)      stress only
  bása (read)     vs basâ (wet)        stress plus glottal stop
  tubò (growth)   vs tubó (sugarcane)  final stress; glottal stop only

The whole word is synthesized with a Spanish voice using the written accent to
place stress. For the glottal member, a short abrupt cut plus silence
approximates the final glottal stop.

Requirements:
  python3 -m pip install --user edge-tts
  ffmpeg in PATH, or FFMPEG=/path/to/ffmpeg

Run:
  npm run audio:pairs
"""

import asyncio
import os
import subprocess
import tempfile
from pathlib import Path

import edge_tts

VOICE = os.environ.get("TAGALOG_PAIR_VOICE", "es-ES-ElviraNeural")
RATE = os.environ.get("TAGALOG_PAIR_RATE", "-8%")
FFMPEG = os.environ.get("FFMPEG", "ffmpeg")
OUT_DIR = Path("public/audio/custom")
OVERRIDES_PATH = Path("src/content/audio-overrides.ts")
TEMP_DIR = Path(tempfile.mkdtemp(prefix="tagalog-pairs-"))

# Files from the earlier first-stress/final-stress experiment.
OLD_FILES = [
    "basa-first-stress.mp3",
    "basa-final-stress.mp3",
    "tubo-first-stress.mp3",
    "tubo-final-stress.mp3",
]


def run(args: list[str]) -> None:
    subprocess.run([FFMPEG, "-y", "-loglevel", "error", *args], check=True)


async def synthesize(text: str, path: Path, attempts: int = 3) -> None:
    for attempt in range(1, attempts + 1):
        try:
            await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(path))
            if path.exists() and path.stat().st_size > 500:
                return
        except Exception:
            pass
        await asyncio.sleep(0.8 * attempt)
    raise RuntimeError(f"Could not generate audio for: {text}")


def trim_silence(src: Path, dst: Path) -> None:
    run(
        [
            "-i", str(src),
            "-af",
            "silenceremove=start_periods=1:start_duration=0.01:start_threshold=-45dB,"
            "areverse,silenceremove=start_periods=1:start_duration=0.01:start_threshold=-45dB,areverse",
            "-ar", "24000",
            "-ac", "1",
            str(dst),
        ]
    )


def encode(src: Path, dst: Path) -> None:
    run(
        [
            "-i", str(src),
            "-codec:a", "libmp3lame",
            "-b:a", "48k",
            "-ar", "24000",
            "-ac", "1",
            str(dst),
        ]
    )


async def build(word: str, spoken_text: str, glottal: bool, filename: str) -> str:
    mp3 = TEMP_DIR / f"{word}.mp3"
    trimmed = TEMP_DIR / f"{word}-trimmed.wav"
    shaped = TEMP_DIR / f"{word}-shaped.wav"
    output = OUT_DIR / filename

    await synthesize(spoken_text, mp3)
    trim_silence(mp3, trimmed)
    if glottal:
        # A short, abrupt cut plus silence approximates a final glottal stop.
        run(
            [
                "-i", str(trimmed),
                "-af", "areverse,atrim=start=0.02,areverse,apad=pad_dur=0.04",
                "-ar", "24000",
                "-ac", "1",
                str(shaped),
            ]
        )
    else:
        shaped = trimmed
    encode(shaped, output)
    print(f"{word}: {output} (spoken as {spoken_text!r}, voice {VOICE})")
    return f"/audio/custom/{filename}"


async def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for old in OLD_FILES:
        (OUT_DIR / old).unlink(missing_ok=True)

    overrides: dict[str, str] = {}
    overrides["báka"] = await build("baka", "báka", False, "baka-first-stress.mp3")
    overrides["baká"] = await build("baka", "baká", False, "baka-final-stress.mp3")
    overrides["bása"] = await build("basa-read", "bása", False, "basa-read.mp3")
    overrides["basâ"] = await build("basa-wet", "basá", True, "basa-wet.mp3")
    overrides["tubò"] = await build("tubo-growth", "tubó", True, "tubo-growth.mp3")
    overrides["tubó"] = await build("tubo-sugarcane", "tubó", False, "tubo-sugarcane.mp3")

    lines = [
        "// Generated by scripts/generate-minimal-pairs.py. Do not edit by hand.",
        "export const AUDIO_OVERRIDES: Record<string, string> = {",
    ]
    for word, path in overrides.items():
        lines.append(f"  {word!r}: {path!r},")
    lines.append("};")
    OVERRIDES_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Overrides written to {OVERRIDES_PATH}")


if __name__ == "__main__":
    asyncio.run(main())
